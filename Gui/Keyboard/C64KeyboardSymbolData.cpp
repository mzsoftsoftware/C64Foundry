const C64KeyboardSymbolBitmap* C64KeyboardSymbolData::bitmap(const C64Key key, const C64KeyboardLabelModifier modifier)
{
    if (modifier != C64KeyboardLabelModifier::Shift && modifier != C64KeyboardLabelModifier::Commodore)
        return nullptr;

    for (const C64KeyboardKeyBitmaps& entry : keyBitmaps)
    {
        if (entry.key != key)
            continue;

        if (modifier == C64KeyboardLabelModifier::Shift)
            return &entry.shift;

        return &entry.commodore;
    }

    return nullptr;
}
